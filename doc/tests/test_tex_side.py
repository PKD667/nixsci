ROOT = Path(__file__).resolve().parents[2]
FILES = ROOT / "doc" / "files"
FIXTURES = Path(__file__).resolve().parent / "fixtures"
CASES = 6
PKGS = f'(builtins.getFlake "path:{ROOT}").inputs.nixpkgs.legacyPackages.x86_64-linux'


def nix_build(expr):
    """The default output of a derivation, built by Nix."""
    r = subprocess.run(["nix", "build", "--impure", "--no-link", "--json", "--expr", expr],
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    return json.loads(r.stdout)[0]["outputs"]["out"]


@pytest.fixture(scope="session")
def tools():
    tex = nix_build(f"let p = {PKGS}; in p.texliveSmall.withPackages (ps: with ps; [ latexmk fontspec tex-gyre ])")
    poppler = nix_build(f"{PKGS}.poppler-utils")
    dejavu = nix_build(f"{PKGS}.dejavu_fonts")
    return {"bin": [f"{tex}/bin", f"{poppler}/bin"], "ttf": f"{dejavu}/share/fonts/truetype/DejaVuSans.ttf"}


def make_tree(dst, tools, *, classopts, uses, fonts, project, style, hand, body):
    """hand=True: generated.tex carries only the values; the document names class and packages."""
    dst.mkdir(parents=True)
    for name in ["nixsci.sty", "nixsci.cls"]:
        shutil.copy(FILES / "shim" / name, dst / name)
    lib = dst / "nixsci"
    lib.mkdir()
    for name in ["nixsci.sty", "nixsci.cls", "nixsci-fonts.sty"]:
        shutil.copy(FILES / name, lib / name)
    gen = ["% generated by the test"]
    if not hand:
        gen.append(r"\nixsci@class{article}{%s}" % ",".join(classopts))
        gen.append(r"\nixsci@medium{}")
        gen += [r"\nixsci@use{ulem}{normalem}"] if uses else []
        gen += [r"\nixsci@project{proj}"] if project else []
        gen += [r"\nixsci@style{deck}"] if style else []
    gen.append(r"\nixsci@defval{demo/final}{0.3}")
    (lib / "generated.tex").write_text("\n".join(gen) + "\n")
    if project:
        shutil.copy(FIXTURES / "proj.sty", lib / "proj.sty")
    if style:
        shutil.copy(FIXTURES / "deck.sty", lib / "deck.sty")
    if fonts:
        fdir = lib / "fonts" / "BerkeleyPatched"
        fdir.mkdir(parents=True)
        shutil.copy(tools["ttf"], fdir / "BerkeleyPatched.ttf")
        (lib / "fonts.tex").write_text(
            r"\nixsci@font{main}{texgyretermes}{}{.otf}{texgyretermes-regular}{texgyretermes-bold}"
            r"{texgyretermes-italic}{texgyretermes-bolditalic}{}{}" "\n"
            r"\nixsci@font{mono}{BerkeleyPatched}{nixsci/fonts/BerkeleyPatched/}{.ttf}{}{}{}{}{1.4}{0.15}" "\n")
    (dst / "main.tex").write_text(body)
    return dst


def document(spec, *, hand):
    """The same text in both forms. The hand form writes the class and packages out."""
    if hand:
        head = "\\documentclass[%s]{article}\n" % ",".join(spec["classopts"])
        if spec["uses"]:
            head += "\\usepackage[normalem]{ulem}\n"
        head += "\\usepackage{nixsci}\n"
        if spec["fonts"]:
            head += "\\usepackage{nixsci-fonts}\n"
        if spec["project"]:
            head += "\\usepackage{proj}\n"
        if spec["style"]:
            head += "\\usepackage{deck}\n"
    else:
        head = "\\documentclass{nixsci}\n"
    words = ["Start \\val{demo/final}"]
    if spec["project"]:
        words.append("\\projmacro")
    if spec["style"]:
        words.append("\\stylemacro")
    if spec["fonts"]:
        words.append("\\texttt{mono}")
    return head + "\\begin{document}\n" + " ".join(words) + ".\n\\end{document}\n"


def compile_(tree, main, tools, *, workdir, engine="lualatex", cwd=None, nixsciroot=None):
    """latexmk under an empty environment. Returns (exit code, log text, pdf path or None)."""
    home, out = workdir / "home", workdir / "out"
    home.mkdir(parents=True, exist_ok=True)
    out.mkdir(parents=True, exist_ok=True)
    env = {"PATH": ":".join(tools["bin"] + ["/usr/bin", "/bin"]), "HOME": str(home), "LANG": "C",
           "TEXMFHOME": "/nonexistent", "TEXINPUTS": f"{tree}:", "SOURCE_DATE_EPOCH": "0"}
    flag = {"lualatex": "-lualatex", "pdflatex": "-pdf"}[engine]
    cmd = ["latexmk", flag, "-interaction=nonstopmode", "-halt-on-error", f"-outdir={out}"]
    if nixsciroot is not None:
        cmd.append(f"-usepretex=\\def\\nixsciroot{{{nixsciroot}}}")
    cmd.append(str(main))
    r = subprocess.run(cmd, cwd=cwd or tree, env=env, capture_output=True, text=True)
    log = (out / "main.log").read_text(errors="replace") if (out / "main.log").exists() else ""
    pdf = out / "main.pdf"
    return r.returncode, log, (pdf if pdf.exists() else None)


def text_of(pdf, tools):
    r = subprocess.run(["pdftotext", str(pdf), "-"], capture_output=True, text=True,
                       env={"PATH": ":".join(tools["bin"]), "LANG": "C"})
    assert r.returncode == 0, r.stderr
    return r.stdout


def fonts_of(pdf, tools):
    r = subprocess.run(["pdffonts", str(pdf)], capture_output=True, text=True,
                       env={"PATH": ":".join(tools["bin"]), "LANG": "C"})
    assert r.returncode == 0, r.stderr
    return r.stdout


def check_content(pdf, spec, tools):
    """A law that compares two outputs must also see that each has the content: not empty equality."""
    text = text_of(pdf, tools)
    assert "0.3" in text, text
    assert ("mono" in text) == spec["fonts"], text
    assert ("PROJECTMARK" in text) == spec["project"], text
    assert ("STYLEMARK" in text) == spec["style"], text
    fonts = fonts_of(pdf, tools)
    assert ("TeXGyreTermes" in fonts) == spec["fonts"], fonts
    assert ("DejaVuSans" in fonts) == spec["fonts"], fonts


def random_specs(rng):
    yield dict(classopts=[], uses=False, fonts=False, project=False, style=False)
    for _ in range(CASES - 1):
        yield dict(classopts=rng.sample(["a4paper", "11pt"], rng.randint(0, 2)),
                   uses=rng.random() < 0.5, fonts=rng.random() < 0.5,
                   project=rng.random() < 0.5, style=rng.random() < 0.5)


def test_law1_placement(tmp_path, tools):
    """Law 1: the tree from its root and from another cwd with \\nixsciroot absolute give equal text."""
    for i, spec in enumerate(random_specs(random.Random(20261023))):
        tree = make_tree(tmp_path / f"tree{i}", tools, hand=False, body=document(spec, hand=False), **spec)
        code, log, pdf_root = compile_(tree, tree / "main.tex", tools, workdir=tmp_path / f"root{i}")
        assert code == 0 and pdf_root, (spec, log[-2000:])
        other = tmp_path / f"cwd{i}"
        other.mkdir()
        code, log, pdf_other = compile_(tree, tree / "main.tex", tools, workdir=tmp_path / f"other{i}",
                                        cwd=other, nixsciroot=f"{tree}/")
        assert code == 0 and pdf_other, (spec, log[-2000:])
        check_content(pdf_root, spec, tools)
        assert text_of(pdf_root, tools) == text_of(pdf_other, tools), spec


def test_law2_abstract_equals_explicit(tmp_path, tools):
    """Law 2: \\documentclass{nixsci} equals the hand-written class and packages."""
    for i, spec in enumerate(random_specs(random.Random(20261024))):
        abstract = make_tree(tmp_path / f"abs{i}", tools, hand=False, body=document(spec, hand=False), **spec)
        explicit = make_tree(tmp_path / f"exp{i}", tools, hand=True, body=document(spec, hand=True), **spec)
        code, log, pdf_a = compile_(abstract, abstract / "main.tex", tools, workdir=tmp_path / f"wa{i}")
        assert code == 0 and pdf_a, (spec, log[-2000:])
        code, log, pdf_e = compile_(explicit, explicit / "main.tex", tools, workdir=tmp_path / f"we{i}")
        assert code == 0 and pdf_e, (spec, log[-2000:])
        check_content(pdf_a, spec, tools)
        check_content(pdf_e, spec, tools)
        assert text_of(pdf_a, tools) == text_of(pdf_e, tools), spec


@pytest.mark.parametrize("case", ["font-under-pdflatex", "unknown-val", "unknown-style"])
def test_law3_loud_failure(tmp_path, tools, case):
    """Law 3: a wrong document fails with its message and writes no PDF."""
    spec = dict(classopts=[], uses=False, fonts=case == "font-under-pdflatex", project=False, style=False)
    body = document(spec, hand=False)
    message = {"font-under-pdflatex": "fonts need lualatex or xelatex",
               "unknown-val": "no value `nope/key'",
               "unknown-style": "unknown nixsci style `nope'"}[case]
    if case == "unknown-val":
        body = body.replace("\\val{demo/final}", "\\val{nope/key}")
    if case == "unknown-style":
        body = body.replace("\\begin{document}", "\\nixscistyle{nope}\n\\begin{document}")
    tree = make_tree(tmp_path / "tree", tools, hand=False, body=body, **spec)
    code, log, pdf = compile_(tree, tree / "main.tex", tools, workdir=tmp_path / "w",
                              engine="pdflatex" if case == "font-under-pdflatex" else "lualatex")
    assert code != 0 and pdf is None, log[-2000:]
    assert message in log, log[-2000:]
